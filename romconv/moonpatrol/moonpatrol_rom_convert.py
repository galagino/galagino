print(f"\n=== DONE === All files written to {OUT_DIR}")
for fn in sorted(os.listdir(OUT_DIR)):
    if fn.endswith('.h'):
        print(f"  {fn:35s} {os.path.getsize(os.path.join(OUT_DIR, fn)):8d} bytes")
