#!/usr/bin/env python3
"""
ROM converter for Moon Patrol (Irem 1982) — GALAGINO project
Hardware: Irem M52 board
  Main CPU: Z80 @ 3.072 MHz
  Audio CPU: M6803 @ 3.579545 MHz
  Sound: 2x AY-3-8910 @ 894886 Hz + MSM5205 ADPCM
  Video: 240x252 visible, ROT0 (landscape)
  Tiles: 8x8, 2bpp planar, MSB-first (512 tiles from 2x 4KB ROMs)
  Sprites: 16x16, 3bpp, MSB-first (128 sprites, 3rd plane zero-filled)
  Backgrounds: 3 layers (mountains, hills, city), 256x64 each
    Format: interleaved bitplane {4,0} — 4 pixels/byte
    Scroll: mountains=ports 0x80/0xA0, hills/city=ports 0x40/0x60
    MAME offsets: ypos += 16, xpos += 124

Generates:
  moonpatrol_rom.h        - 16KB CPU ROM
  moonpatrol_snd_rom.h    - 16KB sound ROM container (4KB actual at end)
  moonpatrol_tilemap.h    - 512 tiles (8x8, 2bpp, MSB-first packed)
  moonpatrol_spritemap.h  - 128 sprites x 4 orientations (16x16, 3bpp, MSB-first)
  moonpatrol_bgmap.h      - 3 background layers (256x64, raw ROM bytes)
  moonpatrol_cmap.h       - color lookup tables (tiles, sprites, backgrounds)
  moonpatrol_dipswitches.h - DIP switch defaults (1C/1C, 3 lives)

Usage:
  python3 moonpatrol_rom_convert.py
"""

import os
import sys
import zipfile, sys, os

# ── ROM ZIP location ──
ZIP_PATHS = [
  "../../romszip/mpatrol.zip"
]
romzip = None
for p in ZIP_PATHS:
    if os.path.exists(p):
        romzip = p
        break

if romzip is None:
    print("ERROR: mpatrol.zip not found! Searched:")
    for p in ZIP_PATHS:
        print(f"  {p}")
    sys.exit(1)

print(f"Using ROM ZIP: {romzip}")
z = zipfile.ZipFile(romzip)

def load(name):
    data = z.read(name)
    print(f"  Loaded {name}: {len(data)} bytes")
    return data

# ── Output directory (machines/moonpatrol/) ──
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(SCRIPT_DIR, "..", "..", "source", "src", "machines", "moonpatrol")
os.makedirs(OUT_DIR, exist_ok=True)
print(f"Output dir: {OUT_DIR}")

# ============================================================
# Helper: write a byte array
# ============================================================
def write_byte_array(filename, varname, data, comment=""):
    path = os.path.join(OUT_DIR, filename)
    with open(path, "w") as f:
        f.write(f"// {comment}\n")
        f.write(f"// Auto-generated by romconv_moonpatrol.py\n\n")
        f.write(f"const unsigned char {varname}[] = {{\n")
        for i in range(0, len(data), 16):
            chunk = data[i:i+16]
            f.write("  " + ", ".join(f"0x{b:02x}" for b in chunk) + ",\n")
        f.write("};\n")
    print(f"  Written {filename} ({len(data)} bytes)")

# ============================================================
# 1. CPU ROM (16KB)
# ============================================================
print("\n=== CPU ROM ===")
cpu_rom = load("mpa-1.3m") + load("mpa-2.3l") + load("mpa-3.3k") + load("mpa-4.3j")
assert len(cpu_rom) == 16384
write_byte_array("moonpatrol_rom.h", "moonpatrol_rom", cpu_rom,
                 "Moon Patrol CPU ROM (16KB: 0x0000-0x3FFF)")

# ============================================================
# 2. Sound ROM (4KB in 16KB container)
# ============================================================
print("\n=== Sound ROM ===")
snd_rom_raw = load("mp-s1.1a")
assert len(snd_rom_raw) == 4096
snd_rom = bytearray(b'\xFF' * 16384)
snd_rom[0x3000:0x4000] = snd_rom_raw
write_byte_array("moonpatrol_snd_rom.h", "moonpatrol_snd_rom", bytes(snd_rom),
                 "Moon Patrol Sound ROM (4KB at offset 0x3000, mapped 0xC000-0xFFFF)")

# ============================================================
# 3. Color PROMs → RGB565 palettes
# ============================================================
print("\n=== Color PROMs ===")
prom_tx   = load("mpc-4.2a")   # 512B tile palette (3-3-2 RGB)
prom_bg   = load("mpc-3.1m")   #  32B background palette
prom_spr  = load("mpc-1.1f")   #  32B sprite palette (2-3-3 RGB)
prom_clut = load("mpc-2.2h")   # 256B sprite CLUT

def rgb332_to_565swap(byte_val):
    r = 0x21 * ((byte_val >> 0) & 1) + 0x47 * ((byte_val >> 1) & 1) + 0x97 * ((byte_val >> 2) & 1)
    g = 0x21 * ((byte_val >> 3) & 1) + 0x47 * ((byte_val >> 4) & 1) + 0x97 * ((byte_val >> 5) & 1)
    b = 0x52 * ((byte_val >> 6) & 1) + 0xAD * ((byte_val >> 7) & 1)
    r5, g6, b5 = (r >> 3) & 0x1F, (g >> 2) & 0x3F, (b >> 3) & 0x1F
    val = (r5 << 11) | (g6 << 5) | b5
    return ((val & 0xFF) << 8) | ((val >> 8) & 0xFF)

def spr233_to_565swap(byte_val):
    r = 0x55 * ((byte_val >> 6) & 1) + 0xAA * ((byte_val >> 7) & 1)
    g = 0x21 * ((byte_val >> 3) & 1) + 0x47 * ((byte_val >> 4) & 1) + 0x97 * ((byte_val >> 5) & 1)
    b = 0x21 * ((byte_val >> 0) & 1) + 0x47 * ((byte_val >> 1) & 1) + 0x97 * ((byte_val >> 2) & 1)
    r5, g6, b5 = (r >> 3) & 0x1F, (g >> 2) & 0x3F, (b >> 3) & 0x1F
    val = (r5 << 11) | (g6 << 5) | b5
    return ((val & 0xFF) << 8) | ((val >> 8) & 0xFF)

tile_palette = [rgb332_to_565swap(b) for b in prom_tx]
bg_palette = [rgb332_to_565swap(b) for b in prom_bg]
spr_palette = [spr233_to_565swap(b) for b in prom_spr]
spr_clut_colors = [spr_palette[prom_clut[i] & 0x1F] for i in range(256)]

# Tile colormap: 128 palettes × 4 colors
tile_cmap = []
for pal in range(128):
    tile_cmap.append([tile_palette[pal * 4 + px] if pal * 4 + px < 512 else 0 for px in range(4)])

# Sprite colormap: 16 groups × 8 colors (pixel 0 = transparent)
spr_cmap = []
for group in range(16):
    colors = [0x0000]  # pixel 0 transparent
    for px in range(1, 8):
        idx = group * 8 + px
        colors.append(spr_clut_colors[idx] if idx < 256 else 0)
    spr_cmap.append(colors)

# BG colormaps (hardcoded per MAME palette init)
bg_cmap = [
    [bg_palette[0], bg_palette[4], bg_palette[8], bg_palette[12]],   # bg0 mountains
    [bg_palette[0], bg_palette[1], bg_palette[2], bg_palette[3]],    # bg1 hills
    [bg_palette[0], bg_palette[17], bg_palette[18], bg_palette[19]], # bg2 city
]

cmap_path = os.path.join(OUT_DIR, "moonpatrol_cmap.h")
with open(cmap_path, "w") as f:
    f.write("// Moon Patrol color maps\n// Auto-generated by romconv_moonpatrol.py\n\n")
    f.write("#define MP_TILE_PALETTES 128\n\n")
    f.write("const unsigned short moonpatrol_tile_cmap[][4] = {\n")
    for pal in range(128):
        f.write(f"  {{ {', '.join(f'0x{c:04x}' for c in tile_cmap[pal])} }},\n")
    f.write("};\n\n#define MP_SPRITE_GROUPS 16\n\n")
    f.write("const unsigned short moonpatrol_spr_cmap[][8] = {\n")
    for group in range(16):
        f.write(f"  {{ {', '.join(f'0x{c:04x}' for c in spr_cmap[group])} }},\n")
    f.write("};\n\nconst unsigned short moonpatrol_bg_cmap[][4] = {\n")
    for layer in range(3):
        name = ['mountains', 'hills', 'city'][layer]
        f.write(f"  {{ {', '.join(f'0x{c:04x}' for c in bg_cmap[layer])} }},  // {name}\n")
    f.write("};\n")
print(f"  Written moonpatrol_cmap.h")

# ============================================================
# 4. Tile graphics (512 tiles, 8x8, 2bpp planar, MSB-first)
# ============================================================
print("\n=== Tile Graphics ===")
tile_rom0 = load("mpe-4.3f")
tile_rom1 = load("mpe-5.3e")

NTILES = 512
tile_data = []
for t in range(NTILES):
    rows = []
    for r in range(8):
        byte0 = tile_rom0[t * 8 + r]
        byte1 = tile_rom1[t * 8 + r]
        # MSB-first: bit 7 = pixel 0 (leftmost)
        val = 0
        for x in range(8):
            bit0 = (byte0 >> (7 - x)) & 1
            bit1 = (byte1 >> (7 - x)) & 1
            val |= ((bit0 | (bit1 << 1)) << (x * 2))
        rows.append(val)
    tile_data.append(rows)

tile_path = os.path.join(OUT_DIR, "moonpatrol_tilemap.h")
with open(tile_path, "w") as f:
    f.write(f"// Moon Patrol tiles (512, 8x8, 2bpp MSB-first)\n// Auto-generated\n\n")
    f.write(f"#define MP_NTILES {NTILES}\n\n")
    f.write(f"const unsigned short moonpatrol_tilemap[{NTILES}][8] = {{\n")
    for t in range(NTILES):
        f.write(f"  {{ {', '.join(f'0x{v:04x}' for v in tile_data[t])} }},\n")
    f.write("};\n")
print(f"  Written moonpatrol_tilemap.h ({NTILES} tiles)")

# ============================================================
# 5. Sprite graphics (128 sprites, 16x16, 3bpp, MSB-first)
# ============================================================
print("\n=== Sprite Graphics ===")
spr_rom0 = load("mpb-2.3m")  # plane 1 (bit 1)
spr_rom1 = load("mpb-1.3n")  # plane 0 (bit 0)

NSPRITES = 128  # 4096 / 32 = 128 sprites per plane

def decode_sprite(code):
    rows = []
    for r in range(16):
        pixels = []
        for half in range(2):
            byte_off = code * 32 + r + half * 16
            b1 = spr_rom0[byte_off] if byte_off < len(spr_rom0) else 0
            b0 = spr_rom1[byte_off] if byte_off < len(spr_rom1) else 0
            for x in range(8):
                bit1 = (b1 >> (7 - x)) & 1  # MSB-first
                bit0 = (b0 >> (7 - x)) & 1
                pixels.append((bit1 << 1) | bit0)
        rows.append(pixels)
    return rows

def flip_sprite(rows, flipx, flipy):
    result = []
    for r in range(16):
        row = list(rows[(15 - r) if flipy else r])
        if flipx: row.reverse()
        result.append(row)
    return result

sprite_variants = [[], [], [], []]
for code in range(NSPRITES):
    raw = decode_sprite(code)
    for variant in range(4):
        flipped = flip_sprite(raw, variant & 1, (variant >> 1) & 1)
        packed = []
        for r in range(16):
            lo = sum((flipped[r][x] & 0xF) << (x * 4) for x in range(8))
            hi = sum((flipped[r][8 + x] & 0xF) << (x * 4) for x in range(8))
            packed.extend([lo, hi])
        sprite_variants[variant].append(packed)

spr_path = os.path.join(OUT_DIR, "moonpatrol_spritemap.h")
with open(spr_path, "w") as f:
    f.write(f"// Moon Patrol sprites (128, 16x16, 3bpp, 4 orientations)\n// Auto-generated\n\n")
    f.write(f"#define MP_NSPRITES {NSPRITES}\n\n")
    f.write(f"const unsigned long moonpatrol_spritemap[4][{NSPRITES}][32] = {{\n")
    for v in range(4):
        names = ['normal', 'flipX', 'flipY', 'flipXY']
        f.write(f"  {{ // {names[v]}\n")
        for s in range(NSPRITES):
            f.write(f"    {{ {', '.join(f'0x{val:08x}' for val in sprite_variants[v][s])} }},\n")
        f.write("  },\n")
    f.write("};\n")
print(f"  Written moonpatrol_spritemap.h ({NSPRITES} sprites x 4)")

# ============================================================
# 6. Background graphics (3 layers, 256x64, raw ROM)
# ============================================================
print("\n=== Background Graphics ===")
bg_roms = [load("mpe-1.3l"), load("mpe-2.3k"), load("mpe-3.3h")]

# Raw ROM bytes stored directly. Renderer decodes interleaved bitplane {4,0}:
#   sub = 3 - (x & 3); plane0 = bit(sub); plane1 = bit(sub+4)
# 256x64 image: 64 bytes/row x 64 rows = 4096 bytes per layer
BG_W = 256
BG_H = 64

bg_path = os.path.join(OUT_DIR, "moonpatrol_bgmap.h")
with open(bg_path, "w") as f:
    f.write("// Moon Patrol backgrounds (3 layers, 256x64, interleaved bitplane {4,0})\n")
    f.write("// Auto-generated -- raw ROM bytes, decoded at render time\n")
    f.write("// Decode: sub=3-(x&3); p0=bit(sub); p1=bit(sub+4); pixel=p0|(p1<<1)\n")
    f.write(f"// 64 bytes/row, {BG_H} rows/layer, 4096 bytes each\n\n")
    f.write(f"#define MP_BG_W {BG_W}\n#define MP_BG_H {BG_H}\n\n")
    names = ["mountains", "hills", "city"]
    for layer in range(3):
        f.write(f"const unsigned char moonpatrol_bg{layer}[] = {{  // {names[layer]}\n")
        data = bg_roms[layer]
        for i in range(0, len(data), 16):
            f.write("  " + ", ".join(f"0x{b:02x}" for b in data[i:i+16]) + ",\n")
        f.write("};\n\n")
print(f"  Written moonpatrol_bgmap.h (3 x {BG_W}x{BG_H})")

# ============================================================
# 7. DIP switches (1C/1C, 3 lives, bonus 10K/30K/50K)
# ============================================================
print("\n=== DIP Switches ===")
dip_path = os.path.join(OUT_DIR, "moonpatrol_dipswitches.h")
with open(dip_path, "w") as f:
    f.write("// Moon Patrol DIP switches (from MAME defaults)\n// Auto-generated\n\n")
    f.write("// DSW1: Lives=3(0x02), Bonus=10K/30K/50K(0x0C), Coinage=1C/1C(0xF0)\n")
    f.write("#define MOONPATROL_DSW1  0xFE\n\n")
    f.write("// DSW2: Flip=OFF(0x01), Upright(0x00), defaults\n")
    f.write("#define MOONPATROL_DSW2  0xFD\n")
print(f"  Written moonpatrol_dipswitches.h")

# ============================================================
# 8-9. Logos: TFT and OLED generated from artwork images
#      (use convert_moonpatrol_logo.py or generate manually)
#      If PIL is available, generate from source images.
# ============================================================
print("\n=== Logos ===")
try:
    from noPILno import Image

    # --- TFT Logo (224x96 RLE RGB565) from marquee ---
    LOGO_W, LOGO_H = 224, 96
    tft_src = None
    for p in [r"C:\Users\Tecnico\.claude\image-cache\f3f7128b-27b1-4286-b995-638f15a39316\22.jpeg",
              os.path.join(SCRIPT_DIR, "moonpatrol_marquee.png")]:
        if os.path.exists(p):
            tft_src = p; break

    if tft_src:
        img = Image.open(tft_src)
        target_w = int(LOGO_W * 0.90)  # 90% width
        w, h = img.size
        new_w = target_w
        new_h = int(new_w / (w / h))
        if new_h > LOGO_H: new_h = LOGO_H; new_w = int(new_h * (w / h))
        resized = img.resize((new_w, new_h), Image.LANCZOS)
        canvas = Image.new('RGB', (LOGO_W, LOGO_H), (0, 0, 0))
        canvas.paste(resized, ((LOGO_W - new_w) // 2, (LOGO_H - new_h) // 2))

        def rgb565s(r, g, b):
            v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            return ((v >> 8) & 0xFF) | ((v & 0xFF) << 8)

        px = list(canvas.getdata())
        rgb565 = [rgb565s(p[0], p[1], p[2]) for p in px]
        marker = 1
        while marker in set(rgb565): marker += 1
        rle = [marker]; i = 0
        while i < len(rgb565):
            run = 1
            while i + run < len(rgb565) and rgb565[i + run] == rgb565[i] and run < 65535: run += 1
            if run >= 3 or rgb565[i] == marker:
                rle.extend([marker, run - 1, rgb565[i]]); i += run
            else:
                rle.append(rgb565[i]); i += 1

        with open(os.path.join(OUT_DIR, "moonpatrol_logo.h"), 'w') as f:
            f.write("// Moon Patrol TFT logo (224x96 RLE RGB565)\n// Auto-generated\n\n")
            f.write("const unsigned short moonpatrol_logo[] = {\n")
            for i in range(0, len(rle), 16):
                f.write("  " + ", ".join(str(v) for v in rle[i:i+16]) + ",\n")
            f.write("};\n")
        print(f"  Written moonpatrol_logo.h ({len(rle)} words)")
    else:
        print("  TFT logo source not found, skipping (use existing)")

    # --- OLED Logo (128x64 XBM, white bg, black text) ---
    oled_src = None
    for p in [r"C:\Users\Tecnico\.claude\image-cache\f3f7128b-27b1-4286-b995-638f15a39316\23.jpeg",
              os.path.join(SCRIPT_DIR, "moonpatrol_text.png")]:
        if os.path.exists(p):
            oled_src = p; break

    if oled_src:
        img = Image.open(oled_src)
        w, h = img.size
        new_w, new_h = 128, int(128 / (w / h))
        if new_h > 64: new_h = 64; new_w = int(64 * (w / h))
        resized = img.resize((new_w, new_h), Image.LANCZOS)
        canvas = Image.new('RGB', (128, 64), (255, 255, 255))
        canvas.paste(resized, ((128 - new_w) // 2, (64 - new_h) // 2))
        gray = list(canvas.convert('L').getdata())
        data = []
        for y in range(64):
            for xb in range(16):
                byte_val = 0
                for bit in range(8):
                    if gray[y * 128 + xb * 8 + bit] > 180:
                        byte_val |= (1 << bit)
                data.append(byte_val)

        with open(os.path.join(OUT_DIR, "moonpatrol_oled_logo.h"), 'w') as f:
            f.write("// Moon Patrol OLED logo (128x64 XBM, white bg + black text)\n// Auto-generated\n\n")
            f.write("#define MoonPatrol_Logo_width 128\n#define MoonPatrol_Logo_height 64\n")
            f.write("const uint8_t MoonPatrol_Logo_bits[] = {\n")
            for i in range(0, len(data), 16):
                f.write("  " + ", ".join(f"0x{b:02X}" for b in data[i:i+16]) + ",\n")
            f.write("};\n")
        print(f"  Written moonpatrol_oled_logo.h ({len(data)} bytes)")
    else:
        print("  OLED logo source not found, skipping (use existing)")

except ImportError:
    print("  PIL not available — logos not generated (use existing .h files)")

