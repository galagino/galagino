// see https://github.com/mamedev/mame/blob/master/src/mame/sega/zaxxon.cpp
// INPUT_PORTS_START(zaxxon), DSW02 (0xc002) / DSW03 (0xc003)
// https://www.arcade-museum.com/tech-center/game-dips/zaxxonj

// DSW02 (0xc002)
#define ZAXXON_DIP_A_BONUS_10000  0b00000011
#define ZAXXON_DIP_A_BONUS_20000  0b00000001
#define ZAXXON_DIP_A_BONUS_30000  0b00000010
#define ZAXXON_DIP_A_BONUS_40000  0b00000000

#define ZAXXON_DIP_A_LIVES_3      0b00110000
#define ZAXXON_DIP_A_LIVES_4      0b00010000
#define ZAXXON_DIP_A_LIVES_5      0b00100000
#define ZAXXON_DIP_A_FREE_PLAY    0b00000000

#define ZAXXON_DIP_A_SOUND_OFF    0b00000000
#define ZAXXON_DIP_A_SOUND_ON     0b01000000

#define ZAXXON_DIP_A_UPRIGHT      0b00000000
#define ZAXXON_DIP_A_COCKTAIL     0b10000000

#define ZAXXON_DIP_A (ZAXXON_DIP_A_BONUS_10000 | ZAXXON_DIP_A_LIVES_5 | ZAXXON_DIP_A_SOUND_ON | ZAXXON_DIP_A_UPRIGHT)

// DSW03 (0xc003) - coin B: bits 0-3, coin A: bits 4-7 (values not monotonic, see MAME source)
// XC_YC = X coins per Y credits. Multi-part names (e.g. 2C1_5C3_6C4) are
// tiered bonus schedules: base rate, then better rates at higher coin counts.
#define ZAXXON_DIP_B_COINB_4C_1C        0b00001111
#define ZAXXON_DIP_B_COINB_3C_1C        0b00000111
#define ZAXXON_DIP_B_COINB_2C_1C        0b00001011
#define ZAXXON_DIP_B_COINB_2C1_5C3_6C4  0b00000110
#define ZAXXON_DIP_B_COINB_2C1_3C2_4C3  0b00001010
#define ZAXXON_DIP_B_COINB_1C_1C        0b00000011
#define ZAXXON_DIP_B_COINB_1C1_5C6      0b00000010
#define ZAXXON_DIP_B_COINB_1C1_4C5      0b00001100
#define ZAXXON_DIP_B_COINB_1C1_2C3      0b00000100
#define ZAXXON_DIP_B_COINB_1C_2C        0b00001101
#define ZAXXON_DIP_B_COINB_1C2_5C11     0b00001000
#define ZAXXON_DIP_B_COINB_1C2_4C9      0b00000000
#define ZAXXON_DIP_B_COINB_1C_3C        0b00000101
#define ZAXXON_DIP_B_COINB_1C_4C        0b00001001
#define ZAXXON_DIP_B_COINB_1C_5C        0b00000001
#define ZAXXON_DIP_B_COINB_1C_6C        0b00001110

#define ZAXXON_DIP_B_COINA_4C_1C        0b11110000
#define ZAXXON_DIP_B_COINA_3C_1C        0b01110000
#define ZAXXON_DIP_B_COINA_2C_1C        0b10110000
#define ZAXXON_DIP_B_COINA_2C1_5C3_6C4  0b01100000
#define ZAXXON_DIP_B_COINA_2C1_3C2_4C3  0b10100000
#define ZAXXON_DIP_B_COINA_1C_1C        0b00110000
#define ZAXXON_DIP_B_COINA_1C1_5C6      0b00100000
#define ZAXXON_DIP_B_COINA_1C1_4C5      0b11000000
#define ZAXXON_DIP_B_COINA_1C1_2C3      0b01000000
#define ZAXXON_DIP_B_COINA_1C_2C        0b11010000
#define ZAXXON_DIP_B_COINA_1C2_5C11     0b10000000
#define ZAXXON_DIP_B_COINA_1C2_4C9      0b00000000
#define ZAXXON_DIP_B_COINA_1C_3C        0b01010000
#define ZAXXON_DIP_B_COINA_1C_4C        0b10010000
#define ZAXXON_DIP_B_COINA_1C_5C        0b00010000
#define ZAXXON_DIP_B_COINA_1C_6C        0b11100000

#define ZAXXON_DIP_B (ZAXXON_DIP_B_COINB_1C_1C | ZAXXON_DIP_B_COINA_1C_1C)
