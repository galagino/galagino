#ifndef MOONPATROL_DIPSWITCHES_H
#define MOONPATROL_DIPSWITCHES_H


//
// Moon Patrol DIP switches (from MAME defaults)

// DSW1: Lives=3(0x02), Bonus=10K/30K/50K(0x0C), Coinage=1C/1C(0xF0)
#define MOONPATROL_DSW1  0xFE

// DSW2: Flip=OFF(0x01), Upright(0x00), defaults
#define MOONPATROL_DSW2  0xFD

#endif
